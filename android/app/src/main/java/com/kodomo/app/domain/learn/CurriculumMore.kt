    /** A mixed test per grade and subject: questions drawn from every unit of that subject in that grade. */
    fun exams(all: List<StudyUnit>): List<StudyUnit> = all.groupBy { it.grade to it.subject }
        .filter { it.value.size >= 2 }
        .map { (key, list) ->
            val (g, s) = key
            StudyUnit(
                "exam_${g.name.lowercase()}_${s.name.lowercase()}", g, s, "آزمون جامع ${s.label}", "🏅",
                listOf(LessonCard("🏅", "این آزمون از همه‌ی درس‌های ${s.label} ${g.label} سؤال دارد (${list.size.fa()} درس). آماده‌ای؟")),
            ) { r -> list.random(r).make(r) }
        }
