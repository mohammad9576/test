/** Helpers that build multiple-choice exercises with plausible wrong answers. */
internal object Q {
    fun num(prompt: String, answer: Int, explain: String, r: Random, spread: Int = 3, min: Int = 0): Exercise {
        val set = linkedSetOf(answer)
        var guard = 0
        while (set.size < 4 && guard++ < 50) set += (answer + r.nextInt(-spread, spread + 1)).coerceAtLeast(min)
        var extra = 1
        while (set.size < 4) set += answer + spread + extra++
        val opts = set.shuffled(r)
        return Exercise(prompt, opts.map { it.fa() }, opts.indexOf(answer), explain)
    }

    fun pick(prompt: String, correct: String, wrong: List<String>, explain: String, r: Random): Exercise {
        val opts = (wrong.distinct().filter { it != correct }.shuffled(r).take(3) + correct).shuffled(r)
        return Exercise(prompt, opts, opts.indexOf(correct), explain)
    }

    /** A bank of fixed questions: (question, correct, wrong answers, explanation). */
    fun bank(items: List<List<String>>): (Random) -> Exercise = { r ->
        val q = items.random(r)
        pick(q[0], q[1], q.subList(2, q.size - 1), q.last(), r)
    }

    fun ltr(s: String) = "⁦$s⁩"
}

