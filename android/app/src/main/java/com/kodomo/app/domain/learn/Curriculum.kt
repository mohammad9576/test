    fun forGrade(g: Grade): List<StudyUnit> = units.filter { it.grade == g }

    /** Units of this grade and the previous ones (review), grouped by subject. */
    fun bySubject(g: Grade): Map<Subject, List<StudyUnit>> =
        units.filter { it.grade.ordinal <= g.ordinal }.sortedByDescending { it.grade.ordinal }.groupBy { it.subject }

    fun byId(id: String) = units.firstOrNull { it.id == id }
