package com.kodomo.app.domain.crafts

/** One step of a craft tutorial: a picture (emoji) and a short instruction. */
data class CraftStep(val emoji: String, val text: String)

enum class CraftKind(val label: String, val emoji: String) {
    ORIGAMI("اوریگامی", "🦢"),
    RECYCLE("بازیافتی", "♻️"),
    PAPER("کاغذ و قیچی", "✂️"),
    COLOR("رنگ و خمیر", "🎨"),
    SCIENCE("ساختنی علمی", "🔧"),
}

data class CraftGuide(
    val id: String,
    val title: String,
    val emoji: String,
    val kind: CraftKind,
    val minAge: Int,
    val maxAge: Int,
    val minutes: Int,
    val materials: List<String>,
    val steps: List<CraftStep>,
    /** Needs an adult (scissors, glue gun, hot water…). */
    val withAdult: Boolean = false,
)

