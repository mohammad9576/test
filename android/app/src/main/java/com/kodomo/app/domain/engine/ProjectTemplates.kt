package com.kodomo.app.domain.engine

/**
 * Guided craft projects. Each template fills the four building phases of a Kodomo project (materials, cutting,
 * assembly, decoration) with concrete, safe sub-steps; the fifth phase is always the souvenir photo.
 */
data class ProjectTemplate(
    val title: String,
    val emoji: String,
    val minAge: Int,
    val minutes: Int,
    val materials: List<String>,
    val cutting: List<String>,
    val assembly: List<String>,
    val decoration: List<String>,
) {
    fun phase(step: Int): List<String> = when (step) {
        0 -> materials
        1 -> cutting
        2 -> assembly
        3 -> decoration
        else -> emptyList()
    }
}

